const tabela = Array.from({ length: 256 }, (_, n) => {
  for (let i = 0; i < 8; i++) n = n & 1 ? 0xedb88320 ^ (n >>> 1) : n >>> 1;
  return n >>> 0;
});
function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = tabela[(crc ^ byte) & 255] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}
function empacotar(destino = path.join(__dirname, 'dist', 'lazy-du-agent-panel.zip')) {
  const locais = [], central = []; let offset = 0;
  for (const nome of INCLUIR) {
    if (path.isAbsolute(nome) || nome.split('/').includes('..')) throw Error('Nome de entrega invalido');
    let atual = __dirname;
    for (const parte of nome.split('/')) { atual = path.join(atual, parte); if (fs.lstatSync(atual).isSymbolicLink()) throw Error('Atalho fora da entrega'); }
    let bytes = fs.readFileSync(atual);
    if (nome === 'NOTAS-V2.md') bytes=Buffer.from(bytes.toString('utf8').replace(/\n<!-- SHA-R3-INICIO -->[\s\S]*?<!-- SHA-R3-FIM -->\n?/g, '\n'));
    if (nome === 'package.json') {
      const pkg = JSON.parse(bytes); delete pkg.scripts.test;
      bytes = Buffer.from(JSON.stringify(pkg, null, 2) + '\n');
    }
    const filename = Buffer.from(nome), packed = zlib.deflateRawSync(bytes), crc = crc32(bytes);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x800, 6); local.writeUInt16LE(8, 8);
    local.writeUInt16LE(33, 12); local.writeUInt32LE(crc, 14); local.writeUInt32LE(packed.length, 18); local.writeUInt32LE(bytes.length, 22); local.writeUInt16LE(filename.length, 26);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50); entry.writeUInt16LE(20, 4); entry.writeUInt16LE(20, 6); entry.writeUInt16LE(0x800, 8); entry.writeUInt16LE(8, 10);
    entry.writeUInt16LE(33, 14); entry.writeUInt32LE(crc, 16); entry.writeUInt32LE(packed.length, 20); entry.writeUInt32LE(bytes.length, 24); entry.writeUInt16LE(filename.length, 28); entry.writeUInt32LE(offset, 42);
    locais.push(local, filename, packed); central.push(entry, filename); offset += local.length + filename.length + packed.length;
  }
  const directory = Buffer.concat(central), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50); end.writeUInt16LE(INCLUIR.length, 8); end.writeUInt16LE(INCLUIR.length, 10); end.writeUInt32LE(directory.length, 12); end.writeUInt32LE(offset, 16);
  fs.mkdirSync(path.dirname(destino), { recursive: true });
  const temporario = destino + '.tmp';
  try { fs.writeFileSync(temporario, Buffer.concat([...locais, directory, end])); fs.renameSync(temporario, destino); }
  finally { fs.rmSync(temporario, { force: true }); }
  return destino;
}
